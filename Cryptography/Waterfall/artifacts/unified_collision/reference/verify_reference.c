static uint32_t xt[256];
static uint8_t rol7(uint8_t x){return(uint8_t)((x<<7)|(x>>1));}
static void tables(void){
  for(unsigned i=0;i<256;++i){
    unsigned y=S[i];
    uint8_t a=(uint8_t)(rol7((uint8_t)(y^(y<<2)^(y>>6)^(y<<3)))^0x3b);
    uint8_t b=(uint8_t)((y^(y<<5)^(y>>3)^(y>>7))^0x95);
    uint8_t c=(uint8_t)((y^(y<<7)^(y>>1)^(y>>5))^0x6a);
    xt[i]=(y^i)|((uint32_t)a<<8)|((uint32_t)b<<16)|((uint32_t)c<<24);
  }
}
static uint32_t box(uint32_t x){
  for(unsigned r=0;r<4;++r){x^=xt[x&255];x=(x>>8)|(x<<24);}return x;
}
struct Hash {
  uint32_t s1[16],s2[7],s3[6],p2[32],p3[32];
  unsigned i1,i2,i3,ip,used;
  uint64_t blocks;
  uint8_t pending[64];
};
static void init(struct Hash*h){memset(h,0,sizeof(*h));h->s2[0]=256;h->i1=15;h->i2=6;h->i3=5;h->ip=31;}
static void step(struct Hash*h,uint32_t u){
  uint32_t a=h->s1[h->i1],b=h->s2[h->i2],c=h->s3[h->i3];
  h->i1=(h->i1+1)&15;h->i2=(h->i2+1)%7;h->i3=(h->i3+1)%6;
  a=box(a^h->s1[h->i1]^u);b=box(b^h->s2[h->i2]^u^1);c=box(c^h->s3[h->i3]^u^2);
  h->s1[h->i1]=a;h->s2[h->i2]=b;h->s3[h->i3]=c;
  h->ip=(h->ip+1)&31;h->p2[h->ip]^=b;h->p3[h->ip]^=c;
}
static uint32_t little(const uint8_t*p){return p[0]|((uint32_t)p[1]<<8)|((uint32_t)p[2]<<16)|((uint32_t)p[3]<<24);}
static void slab(struct Hash*h,const uint8_t*p){for(unsigned q=0;q<16;++q)step(h,little(p+4*q));++h->blocks;step(h,(uint32_t)h->blocks);}
static void update(struct Hash*h,const uint8_t*p,size_t n){
  while(n){unsigned take=64-h->used;if(take>n)take=(unsigned)n;
    memcpy(h->pending+h->used,p,take);h->used+=take;p+=take;n-=take;
    if(h->used==64){slab(h,h->pending);h->used=0;}}
}
